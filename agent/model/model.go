// Package model provides provider-independent model operations for Go
// applications. It does not create an agent Host or a JavaScript runtime.
package model

import (
	"context"

	"forge.harakara.site/littleisland/noe/v2/internal/agent/provider"
	"forge.harakara.site/littleisland/noe/v2/internal/decision"
	imageapi "forge.harakara.site/littleisland/noe/v2/internal/image"
)

// Request is one assistant response request using provider-independent JSON.
type Request = provider.Request

// Response contains the assistant message, finish reason, and usage JSON.
type Response = provider.Response

// StreamEvent is a text fragment observed while a provider response streams.
type StreamEvent = provider.StreamEvent

// Model is public model catalog data.
type Model = provider.Model

// ModelQuery filters the public model catalog.
type ModelQuery = provider.ModelQuery

// DecisionRequest is one structured decision request.
type DecisionRequest = decision.Request

// DecisionResponse contains the provider's validated decision response.
type DecisionResponse = decision.Response

// ImageRequest asks a provider to generate image bytes. Saving is left to the
// caller, so the request has no output path.
type ImageRequest = imageapi.GenerationRequest

// GeneratedImage contains generated bytes and provider metadata.
type GeneratedImage = imageapi.Generated

// ImageError classifies image generation failures.
type ImageError = imageapi.Error

// Provider generates one assistant response and can be supplied to Options
// instead of using the built-in provider definitions.
type Provider interface {
	Generate(context.Context, Request) (Response, error)
}

// DecisionProvider performs structured decisions.
type DecisionProvider interface {
	Decide(context.Context, DecisionRequest) (DecisionResponse, error)
}

// ImageProvider generates image bytes without choosing where they are saved.
type ImageProvider interface {
	GenerateImage(context.Context, ImageRequest) (GeneratedImage, error)
}

// HTTPClient is the borrowed transport used by built-in provider adapters.
type HTTPClient = provider.HTTPClient

// CredentialFiles provides explicit per-provider credential locations.
type CredentialFiles = provider.CredentialFiles
